function fallbackBlurb(tag) {
    let hash = 0;
    for (let i = 0; i < tag.length; i += 1) {
        hash = ((hash << 5) - hash + tag.charCodeAt(i)) | 0;
    }
    const pick = FALLBACKS[Math.abs(hash) % FALLBACKS.length];
    return pick(tag);
}

/** @param {string} tag */
export function describeMrDiscoTopic(tag) {
    const key = String(tag || '').trim().toLowerCase();
    if (!key) return '';
    return MR_DISCO_TOPIC_BLURBS[key] || MR_DISCO_TOPIC_BLURBS[key.replace(/\s+/g, '-')] || fallbackBlurb(key);
}

/**
 * Pick a few of an article's tags as exploration topics, preferring specific ones.
 * @param {string[]} [tags]
 * @param {number} [limit]
 */
export function pickMrDiscoTopics(tags = [], limit = 3) {
    const unique = [...new Set(tags.map((tag) => String(tag || '').trim()).filter(Boolean))];
    const specific = unique.filter((tag) => !GENERIC_TAGS.has(tag.toLowerCase()));
    const generic = unique.filter((tag) => GENERIC_TAGS.has(tag.toLowerCase()));
    return [...specific, ...generic].slice(0, limit);
}
